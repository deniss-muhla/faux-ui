#!/usr/bin/env node

/**
 * Regenerates the small Unicode lookup tables used by faux-ui's cellizer.
 *
 * Runtime code intentionally has no Unicode package dependency. This script
 * downloads the pinned Unicode Character Database release and commits the
 * generated tables into the package instead.
 */

import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const unicodeVersion = "17.0.0";
const base = `https://www.unicode.org/Public/${unicodeVersion}/ucd`;
const sources = {
  grapheme: `${base}/auxiliary/GraphemeBreakProperty.txt`,
  emoji: `${base}/emoji/emoji-data.txt`,
  derived: `${base}/DerivedCoreProperties.txt`,
  eastAsianWidth: `${base}/EastAsianWidth.txt`,
};

const graphemeCategories = {
  CR: 1,
  LF: 2,
  Control: 3,
  Extend: 4,
  ZWJ: 5,
  Regional_Indicator: 6,
  Prepend: 7,
  SpacingMark: 8,
  L: 9,
  V: 10,
  T: 11,
  LV: 12,
  LVT: 13,
};

const indicCategories = {
  Consonant: 1,
  Extend: 2,
  Linker: 3,
};

const downloaded = Object.fromEntries(
  await Promise.all(
    Object.entries(sources).map(async ([name, url]) => {
      const response = await fetch(url);
      if (!response.ok) {
        throw new Error(`Failed to fetch ${url}: ${response.status}`);
      }
      return [name, await response.text()];
    }),
  ),
);

function parseCodeRange(raw) {
  const [first, last = first] = raw.trim().split("..");
  return [Number.parseInt(first, 16), Number.parseInt(last, 16)];
}

function mergeRanges(ranges) {
  const sorted = ranges.toSorted((a, b) => a[0] - b[0] || a[1] - b[1]);
  const result = [];
  for (const [start, end] of sorted) {
    const previous = result.at(-1);
    if (previous !== undefined && start <= previous[1] + 1) {
      previous[1] = Math.max(previous[1], end);
    } else {
      result.push([start, end]);
    }
  }
  return result;
}

function mergeCategorizedRanges(ranges) {
  const sorted = ranges.toSorted((a, b) => a[0] - b[0] || a[1] - b[1]);
  const result = [];
  for (const [start, end, category] of sorted) {
    const previous = result.at(-1);
    if (
      previous !== undefined &&
      previous[2] === category &&
      start === previous[1] + 1
    ) {
      previous[1] = end;
    } else {
      result.push([start, end, category]);
    }
  }
  return result;
}

function parsePropertyFile(text, wanted) {
  const result = [];
  for (const line of text.split("\n")) {
    const match = /^\s*([0-9A-F]+(?:\.\.[0-9A-F]+)?)\s*;\s*([^ #;]+)/u.exec(
      line,
    );
    if (match === null || !wanted.has(match[2])) continue;
    result.push(parseCodeRange(match[1]));
  }
  return mergeRanges(result);
}

const grapheme = [];
for (const line of downloaded.grapheme.split("\n")) {
  const match = /^\s*([0-9A-F]+(?:\.\.[0-9A-F]+)?)\s*;\s*([^ #;]+)/u.exec(
    line,
  );
  if (match === null) continue;
  const category = graphemeCategories[match[2]];
  if (category === undefined) continue;
  const [start, end] = parseCodeRange(match[1]);
  grapheme.push([start, end, category]);
}

const indic = [];
for (const line of downloaded.derived.split("\n")) {
  const match = /^\s*([0-9A-F]+(?:\.\.[0-9A-F]+)?)\s*;\s*InCB\s*;\s*([^ #;]+)/u.exec(
    line,
  );
  if (match === null) continue;
  const category = indicCategories[match[2]];
  if (category === undefined) continue;
  const [start, end] = parseCodeRange(match[1]);
  indic.push([start, end, category]);
}

const extendedPictographic = parsePropertyFile(
  downloaded.emoji,
  new Set(["Extended_Pictographic"]),
);
const emojiPresentation = parsePropertyFile(
  downloaded.emoji,
  new Set(["Emoji_Presentation"]),
);
const wide = parsePropertyFile(downloaded.eastAsianWidth, new Set(["W", "F"]));

function hex(value) {
  return `0x${value.toString(16).toUpperCase()}`;
}

function emitFlat(name, ranges) {
  const values = ranges.flat().map(hex);
  const lines = [];
  for (let index = 0; index < values.length; index += 12) {
    lines.push(`  ${values.slice(index, index + 12).join(", ")},`);
  }
  return `export const ${name}: readonly number[] = [\n${lines.join("\n")}\n];`;
}

const output = `/* eslint-disable */
/**
 * Generated by scripts/generate-unicode-data.mjs from Unicode ${unicodeVersion}.
 *
 * Unicode data files are distributed under the Unicode License v3:
 * https://www.unicode.org/license.txt
 * Do not edit this file by hand.
 */

export const UNICODE_VERSION = "${unicodeVersion}";

${emitFlat("GRAPHEME_RANGES", mergeCategorizedRanges(grapheme))}

${emitFlat("INDIC_CONJUNCT_RANGES", mergeCategorizedRanges(indic))}

${emitFlat("EXTENDED_PICTOGRAPHIC_RANGES", extendedPictographic)}

${emitFlat("EMOJI_PRESENTATION_RANGES", emojiPresentation)}

${emitFlat("WIDE_RANGES", wide)}
`;

const destination = resolve(
  import.meta.dirname,
  "../packages/ui/src/internal/unicode-data.ts",
);
await writeFile(destination, output);
console.log(`Wrote ${destination} (${output.length} bytes)`);
